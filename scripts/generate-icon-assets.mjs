import { readFile, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import dynamicIconImports from "lucide-react/dynamicIconImports.js";

const root = process.cwd();
const sourcePath = path.join(root, "catalog/icon-catalog.json");
const spritePath = path.join(root, "public/icons/lucide-nodes.svg");
const metadataPath = path.join(root, "src/generated/iconCatalog.ts");
const registryPath = path.join(root, "src/generated/iconRegistry.ts");
const catalog = JSON.parse(await readFile(sourcePath, "utf8"));

if (catalog.set !== "lucide") throw new Error("The node icon catalog must use the lucide set.");
const packageJson = JSON.parse(await readFile(path.join(root, "node_modules/lucide-react/package.json"), "utf8"));
if (packageJson.version !== catalog.packageVersion) {
  throw new Error(`Icon catalog expects lucide-react ${catalog.packageVersion}, found ${packageJson.version}.`);
}

const names = new Set();
const symbols = [];
for (const icon of catalog.icons) {
  if (names.has(icon.name)) throw new Error(`Duplicate icon '${icon.name}' in ${sourcePath}.`);
  names.add(icon.name);
  const load = dynamicIconImports[icon.name];
  if (!load) throw new Error(`Lucide ${catalog.packageVersion} does not contain '${icon.name}'.`);
  const component = (await load()).default;
  const markup = renderToStaticMarkup(createElement(component, { "aria-hidden": "true" }));
  const inner = markup.replace(/^<svg[^>]*>/u, "").replace(/<\/svg>$/u, "");
  symbols.push(`<symbol id="lucide-${icon.name}" viewBox="0 0 24 24">${inner}</symbol>`);
}

for (const [alias, canonical] of Object.entries(catalog.aliases)) {
  if (!names.has(canonical)) throw new Error(`Icon alias '${alias}' points to missing '${canonical}'.`);
}

const sprite = [
  `<!-- Generated by scripts/generate-icon-assets.mjs from lucide-react ${catalog.packageVersion}. -->`,
  '<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true">',
  "<defs>",
  ...symbols,
  "</defs>",
  "</svg>",
  "",
].join("\n");
const registry =
  `// Generated by scripts/generate-icon-assets.mjs. Do not edit.\n` +
  `export const ICON_SET = ${JSON.stringify(catalog.set)} as const;\n` +
  `export const ICON_PACKAGE_VERSION = ${JSON.stringify(catalog.packageVersion)} as const;\n` +
  `export const ICON_SPRITE_PATH = "icons/lucide-nodes.svg" as const;\n` +
  `export const ICON_ALIASES = ${JSON.stringify(catalog.aliases, null, 2)} as const;\n` +
  `export const ICON_NAMES = ${JSON.stringify([...names], null, 2)} as const;\n`;
const metadata =
  `// Generated by scripts/generate-icon-assets.mjs. Do not edit.\n` +
  `export const ICON_CATALOG = ${JSON.stringify(catalog.icons, null, 2)} as const;\n`;

await mkdir(path.dirname(spritePath), { recursive: true });
await writeFile(spritePath, sprite, "utf8");
await writeFile(metadataPath, metadata, "utf8");
await writeFile(registryPath, registry, "utf8");
