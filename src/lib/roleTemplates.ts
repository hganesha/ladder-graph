export interface RoleTemplate {
  id: string;
  path: string;
  name: string;
  role: string;
  prompt: string;
  skills: string[];
  tools: string[];
  connectors?: string[];
  permissions?: string[];
}

function role(
  id: string,
  path: string,
  name: string,
  roleName: string,
  prompt: string,
  skills: string[],
  tools: string[] = ["read"],
  connectors: string[] = [],
  permissions: string[] = ["read-only"],
): RoleTemplate {
  return { id, path, name, role: roleName, prompt, skills, tools, connectors, permissions };
}

